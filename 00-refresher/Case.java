public class Case {
    public static void main(String[] args) {
        int v = -1;
        switch (v) {
            case -1: {
                System.out.println("Value is Negative");
                break;
            }
            case 0: {
                System.out.println("Value is zero");
                break;
            }
            case 1: {
                System.out.println("Value is positive");
                break;
            }
        }
    } 
}